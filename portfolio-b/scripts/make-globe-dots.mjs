// Builds src/globeDots.js: evenly spaced land dots on a sphere plus denser
// dots for the client countries, from Natural Earth (public domain) via world-atlas.
import fs from 'fs';
import { feature } from 'topojson-client';
import { geoContains, geoCentroid } from 'd3-geo';
const out = process.argv[2];
const land = feature(JSON.parse(fs.readFileSync('node_modules/world-atlas/land-50m.json')), 'land');
const countries = feature(JSON.parse(fs.readFileSync('node_modules/world-atlas/countries-50m.json')), 'countries');
const ids = { US: '840', AE: '784', AU: '036', GB: '826', IN: '356' };
const byCode = Object.fromEntries(Object.entries(ids).map(([k, id]) => [k, countries.features.find((f) => f.id === id)]));
function fib(n, fn) {
  const ga = Math.PI * (3 - Math.sqrt(5));
  for (let i = 0; i < n; i++) {
    const y = 1 - (i / (n - 1)) * 2;
    const lat = Math.asin(y) * 180 / Math.PI;
    const lon = ((((ga * i) * 180 / Math.PI) % 360) + 540) % 360 - 180;
    fn(lon, lat);
  }
}
const r1 = (v) => Math.round(v * 10) / 10;
const LAND = [];
fib(26000, (lon, lat) => { if (lat > -60 && geoContains(land, [lon, lat])) LAND.push(r1(lon), r1(lat)); });
// small countries need a finer grid to read as a shape
const density = { US: 26000 * 3, AE: 26000 * 60, AU: 26000 * 3, GB: 26000 * 25, IN: 26000 * 4 };
const REGIONS = {}; const CENTROIDS = {};
for (const [code, f] of Object.entries(byCode)) {
  const pts = [];
  // only test points inside the country's bounding box for speed
  const [[x0, y0], [x1, y1]] = (await import('d3-geo')).geoBounds(code === 'US' ? { type: 'Feature', geometry: { type: 'Polygon', coordinates: [[[-125, 24], [-66, 24], [-66, 50], [-125, 50], [-125, 24]]] } } : f);
  fib(density[code], (lon, lat) => {
    if (lon < x0 - 1 || lon > x1 + 1 || lat < y0 - 1 || lat > y1 + 1) return;
    if (geoContains(f, [lon, lat])) pts.push(r1(lon), r1(lat));
  });
  REGIONS[code] = pts;
  const c = code === 'US' ? [-98.5, 39.5] : geoCentroid(f);
  CENTROIDS[code] = [r1(c[0]), r1(c[1])];
  console.error(code, pts.length / 2, CENTROIDS[code]);
}
console.error('land', LAND.length / 2);
fs.writeFileSync(out, `// Generated by scripts/make-globe-dots.mjs from Natural Earth 1:50m (public domain).
// Flat [lon, lat, lon, lat, ...] arrays in degrees.
export const LAND = ${JSON.stringify(LAND)};
export const REGIONS = ${JSON.stringify(REGIONS)};
export const CENTROIDS = ${JSON.stringify(CENTROIDS)};
`);
